export function computeSharpness(s: RigState): number {
  const coarseTarget = s.objectivePower === 10 ? 0.45 : s.objectivePower === 45 ? 0.65 : 0.78;
  const fineTarget = 0.72;
  const errC = Math.abs(s.coarseFocus - coarseTarget) * 180;
  const errF = Math.abs(s.fineFocus - fineTarget) * 90;
  const lightPenalty = Math.abs(s.mirrorAngle - 0.45) * 35;
  const slideMult = s.slidePlaced ? 1 : 0.1;
  return Math.max(5, Math.min(100, Math.round((100 - errC - errF - lightPenalty) * slideMult)));
}

function makeMicroscopyExp(
  num: number,
  title: string,
  shortTitle: string,
  subMode: string,
  summary: string,
  stepsText: [string, string, string],
  formulaLabel: string,
  obsLabel: string,
  expectedVal: number,
  unit: string,
  eyepieceCaption: string
): ExperimentConfig {
  return {
    id: `bio-${num}`,
    number: num,
    discipline: 'Biology',
    title,
    shortTitle,
    rigType: 'biology_microscopy',
    subMode,
    summary,
    apparatusList: ['Compound Microscope (10×/45×/100×)', 'Prepared / Temporary Glass Slide', 'Safranin / Acetocarmine'],
    cameraPresets: BIO_CAMERAS,
    eyepieceType: subMode,
    eyepieceCaption,
    steps: [
      {
        id: `b${num}-s1`,
        instruction: stepsText[0],
        hint: 'Click Place & Stain Slide on Stage and adjust Substage Mirror to 0.45.',
        check: (s) => s.slidePlaced && s.mirrorAngle >= 0.3,
      },
      {
        id: `b${num}-s2`,
        instruction: stepsText[1],
        hint: 'Turn Coarse Focus (~0.65) and Fine Focus (~0.72) until Sharpness > 90%.',
        check: (s) => s.slidePlaced && computeSharpness(s) >= 90,
      },
      {
        id: `b${num}-s3`,
        instruction: stepsText[2],
        hint: 'Switch to 45× High Power objective and click Capture Microscopic Observation.',
        check: (s) => computeSharpness(s) >= 90 && s.objectivePower >= 45 && s.measurementCount >= 1,
      },
    ],
    controls: [
      { id: 'slide', label: 'Place & Stain Slide on Stage', type: 'button', action: 'place_slide' },
      { id: 'mirror', label: 'Substage Mirror Illumination', type: 'slider', min: 0, max: 0.9, step: 0.05, action: 'set_mirror', getValue: (s) => s.mirrorAngle },
      {
        id: 'obj',
        label: 'Objective Lens Power',
        type: 'select',
        options: [
          { label: '10× Low Power', value: 10 },
          { label: '45× High Power', value: 45 },
          { label: '100× Oil Immersion', value: 100 },
        ],
        action: 'set_objective',
        getValue: (s) => s.objectivePower,
      },
      { id: 'coarse', label: 'Coarse Focus Knob', type: 'slider', min: 0, max: 1, step: 0.02, action: 'set_coarse', getValue: (s) => s.coarseFocus },
      { id: 'fine', label: 'Fine Focus Knob', type: 'slider', min: 0, max: 1, step: 0.02, action: 'set_fine', getValue: (s) => s.fineFocus },
      { id: 'cap', label: 'Capture Microscopic Observation', type: 'button', action: 'capture_reading' },
    ],
    checkSafety: (s, prev) =>
      prev.objectivePower !== 100 && s.objectivePower === 100 && s.coarseFocus > 0.88
        ? 'Objective lens impact warning! Do not use Coarse Focus at high magnification—use Fine Focus only.'
        : null,
    formulaLabel,
    observationFields: [{ key: 'mag', label: obsLabel, unit, placeholder: String(expectedVal), expectedValue: expectedVal }],
    resultLabel: 'Total Magnification (10× Eyepiece × Obj)',
    resultUnit: '×',
    groundTruthResult: 450,
    tolerancePct: 5,
    getLiveReadout: (s) => [
      { label: 'Objective', value: `${s.objectivePower}× (${s.objectivePower * 10}× Total)` },
      { label: 'Eyepiece Sharpness', value: `${computeSharpness(s)}%` },
    ],
  };
}

